// Expand the CSS geometry shipped with the individual Iconify components into ordinary SVG
// attributes and write them as one sprite (plus a little metadata), so icons render offline,
// including in browsers without CSS d.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const registry = readFileSync('apps/web/src/lib/icons/registry.ts', 'utf8');
const drawings = new Map<string, { body: string; width: number; height: number }>();
const attributes = new Set([
  'fill',
  'fill-rule',
  'clip-rule',
  'fill-opacity',
  'opacity',
  'stroke',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-miterlimit',
  'stroke-width',
  'd',
  'width',
  'height',
  'x',
  'y',
  'rx',
  'ry',
  'cx',
  'cy',
  'r',
]);
const escape = (value: string) => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;');

for (const match of registry.matchAll(/import (\w+) from '@iconify-svelte\/([^/]+)\/([^']+)';/g)) {
  const [, component, collection, icon] = match;
  const root = resolve('node_modules', '@iconify-svelte', collection);
  const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  const file = resolve(root, pkg.exports[`./${icon}`].svelte);
  const source = readFileSync(file, 'utf8');
  const viewBox = JSON.parse(source.match(/const viewBox = (\{.*?\});/)![1]);
  let body = source.match(/const content = `([^`]+)`;/)![1];
  const rules = new Map<string, string>();
  for (const css of source.matchAll(/import '([^']+\.css)';/g)) {
    const content = readFileSync(resolve(dirname(file), css[1]), 'utf8');
    for (const rule of content.matchAll(/\.([\w-]+)\s*\{([^}]+)\}/g)) {
      const values = [...rule[2].matchAll(/([\w-]+):\s*([^;]+);/g)].map((declaration) => {
        const [, property, original] = declaration;
        if (!attributes.has(property)) throw new Error(`Unsupported SVG property: ${property}`);
        let value = original.trim();
        if (property === 'd') value = JSON.parse(value.slice(5, -1));
        else value = value.replace(/^var\([^,]+,\s*([^)]+)\)$/, '$1').replace(/px$/, '');
        return `${property}="${escape(value)}"`;
      });
      rules.set(rule[1], values.join(' '));
    }
  }
  body = body.replace(/class="([^"]+)"/g, (_, classes: string) =>
    classes
      .split(/\s+/)
      .map((name) => {
        const attrs = rules.get(name);
        if (attrs === undefined) throw new Error(`Missing SVG rule: ${name}`);
        return attrs;
      })
      .join(' '),
  );
  drawings.set(component, { body, ...viewBox });
}

const data = Object.fromEntries(
  [
    ...registry.split('export const ICONS = {')[1].matchAll(/\s*(?:'([^']+)'|([\w-]+)):\s*(\w+),/g),
  ].map(([, quoted, bare, component]) => {
    const drawing = drawings.get(component);
    if (!drawing) throw new Error(`Missing drawing: ${component}`);
    return [quoted ?? bare, drawing];
  }),
);

// The browser draws icons from one cached sprite (<use href="sprite#id">), so pages carry neither
// the geometry in their HTML nor the drawings in a script. An animated icon also gets a `--still`
// symbol without its animation, for reduced motion.
const symbolId = (name: string) => name.replaceAll(':', '--');
const symbols: string[] = [];
const animated: string[] = [];
for (const [name, drawing] of Object.entries(data)) {
  const viewBox = `0 0 ${drawing.width} ${drawing.height}`;
  symbols.push(`<symbol id="${symbolId(name)}" viewBox="${viewBox}">${drawing.body}</symbol>`);
  if (drawing.body.includes('<animateTransform')) {
    animated.push(name);
    const still = drawing.body.replace(/<animateTransform[^>]*\/>/g, '');
    symbols.push(`<symbol id="${symbolId(name)}--still" viewBox="${viewBox}">${still}</symbol>`);
  }
}
writeFileSync(
  'apps/web/src/lib/icons/sprite.generated.svg',
  `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
);
const meeple = data['game-icons:meeple'].body.match(/ d="([^"]+)"/)?.[1];
if (!meeple) throw new Error('Missing the meeple path');
const metaOut = 'apps/web/src/lib/icons/sprite.generated.ts';
const meta = `// Generated by bun run icons. Do not edit.\n// Icons with an animation, which also have a \`--still\` symbol in the sprite.\nexport const ANIMATED_ICONS: readonly string[] = ${JSON.stringify(animated)};\n// Every icon name, to check a stored name before drawing it.\nexport const ICON_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(Object.keys(data))});\n// The meeple's path, for the chairs that draw it inline (Chair.svelte).\nexport const MEEPLE_PATH = ${JSON.stringify(meeple)};\n`;
writeFileSync(
  metaOut,
  await format(meta, { ...(await resolveConfig(metaOut)), filepath: metaOut }),
);

console.log(`icons: ${drawings.size} local SVG drawings`);
